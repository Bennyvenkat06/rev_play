import { RevisionNote } from '../types/notes';

/**
 * Formats a RevisionNote object into a clean, human-readable ASCII plain-text document.
 */
export function formatRevisionNoteAsText(note: RevisionNote): string {
  const divider = '='.repeat(78);
  const subDivider = '-'.repeat(78);

  let text = `${divider}\n`;
  text += `REVPLAY — SYLLABUS REVISION MASTER NOTES\n`;
  text += `${note.courseCode}: ${note.courseName}\n`;
  text += `${divider}\n\n`;

  text += `UNIT:               ${note.unitName}\n`;
  text += `TOPIC:              ${note.title}\n`;
  text += `SUBTITLE:           ${note.subtitle}\n`;
  text += `ASSOCIATED GAME:    ${note.associatedGameTitle} (ID: ${note.associatedGameId})\n`;
  text += `SYLLABUS REF:       ${note.officialSyllabusMapping}\n`;
  text += `STATUS:             ${note.isSupplemental ? 'SUPPLEMENTAL PRACTICE' : 'OFFICIAL JNTUH R25 SYLLABUS'}\n`;
  if (note.supplementalNotice) {
    text += `NOTICE:             ${note.supplementalNotice}\n`;
  }
  text += `EXPORT DATE:        ${new Date().toLocaleString()}\n`;
  text += `\n${divider}\n`;

  // 1. REVISION OBJECTIVE
  text += `\n[1] REVISION OBJECTIVE\n${subDivider}\n`;
  text += `${note.objective}\n`;

  // 2. CONCEPT SUMMARY
  text += `\n[2] CORE CONCEPT SUMMARY\n${subDivider}\n`;
  note.conceptSummary.forEach((point, i) => {
    text += `  * ${point}\n`;
  });

  // 3. SYNTAX & TERMINOLOGY
  text += `\n[3] KEY C SYNTAX & TERMINOLOGY\n${subDivider}\n`;
  note.syntaxAndTerminology.forEach((item) => {
    text += `  * ${item.term.toUpperCase()}:\n`;
    text += `    Definition: ${item.definition}\n`;
    if (item.syntax) {
      text += `    Syntax:     ${item.syntax}\n`;
    }
    text += `\n`;
  });

  // 4. CODE EXAMPLES
  text += `\n[4] ACCURATE C CODE EXAMPLES & PROTOTYPES\n${subDivider}\n`;
  note.codeExamples.forEach((ex, idx) => {
    text += `--- Example ${idx + 1}: ${ex.title} ---\n`;
    text += `${ex.code.trim()}\n\n`;
    text += `Explanation: ${ex.explanation}\n\n`;
  });

  // 5. WORKED TRACE
  if (note.workedTrace) {
    text += `\n[5] STEP-BY-STEP WORKED TRACE\n${subDivider}\n`;
    text += `Description: ${note.workedTrace.description}\n\n`;
    text += `Step | Line Executed                 | Variables / State               | Note\n`;
    text += `-----+-------------------------------+---------------------------------+-------------------------\n`;
    note.workedTrace.steps.forEach((s) => {
      const vars = Object.entries(s.variableState)
        .map(([k, v]) => `${k}=${v}`)
        .join(', ');
      text += ` ${String(s.step).padEnd(3)} | ${s.codeLine.padEnd(29)} | ${vars.padEnd(31)} | ${s.explanation}\n`;
    });
    text += `\nFinal Execution Output: ${note.workedTrace.finalOutput}\n`;
  }

  // 6. COMMON MISTAKES & TRAPS
  text += `\n[6] COMMON MISTAKES & C PITFALLS\n${subDivider}\n`;
  note.commonMistakes.forEach((m, idx) => {
    text += `Mistake #${idx + 1}: ${m.pitfall}\n`;
    text += `  [INCORRECT / UNDEFINED]:\n`;
    m.badCode.split('\n').forEach(line => text += `    ${line}\n`);
    text += `  [CORRECT / SAFE IDIOM]:\n`;
    m.fixedCode.split('\n').forEach(line => text += `    ${line}\n`);
    text += `  Consequence: ${m.consequence}\n\n`;
  });

  // 7. QUICK REVISION CHECKLIST
  text += `\n[7] QUICK REVISION CHECKLIST (EXAM READINESS)\n${subDivider}\n`;
  note.quickChecklist.forEach((item) => {
    text += `  [ ] ${item}\n`;
  });

  // 8. EXAM TIPS
  text += `\n[8] JNTUH EXAM TIPS & STRATEGY\n${subDivider}\n`;
  note.examTips.forEach((tip) => {
    text += `  ! ${tip}\n`;
  });

  text += `\n${divider}\n`;
  text += `Generated by RevPlay Revision Engine — Your Syllabus. Reimagined as a Game.\n`;
  text += `${divider}\n`;

  return text;
}

/**
 * Generates a clean, safe filename for the .txt export.
 * e.g., RevPlay_Unit-I_Loops_Revision-Notes.txt
 */
export function generateNotesFilename(note: RevisionNote): string {
  const sanitize = (s: string) => s.replace(/[^a-zA-Z0-9-_]/g, '-').replace(/-+/g, '-');
  const unitLabel = note.unitId === 'lab' ? 'Lab' : note.unitName.split('—')[0].trim().replace(/\s+/g, '-');
  const topicLabel = sanitize(note.title);
  return `RevPlay_${unitLabel}_${topicLabel}_Revision-Notes.txt`;
}

/**
 * Native browser download of revision notes as a plain-text file.
 * Returns true if download was triggered successfully.
 */
export function downloadRevisionNoteAsText(note: RevisionNote): boolean {
  try {
    const textContent = formatRevisionNoteAsText(note);
    const filename = generateNotesFilename(note);
    const blob = new Blob([textContent], { type: 'text/plain;charset=utf-8' });
    const url = URL.createObjectURL(blob);

    const anchor = document.createElement('a');
    anchor.href = url;
    anchor.download = filename;
    anchor.style.display = 'none';
    document.body.appendChild(anchor);
    anchor.click();

    setTimeout(() => {
      document.body.removeChild(anchor);
      URL.revokeObjectURL(url);
    }, 250);

    return true;
  } catch (err) {
    console.error('Failed to trigger plain-text notes download:', err);
    return false;
  }
}

